#[test]
fn invalid_descriptors_and_end_fade_are_safe() {
    let mut f = Field::new();
    f.step(
        f64::NAN,
        Input {
            level: f64::INFINITY,
            balance: f64::NAN,
        },
    );
    f.step(
        0.1,
        Input {
            level: f64::INFINITY,
            balance: f64::NAN,
        },
    );
    f.set_state(State::Ended);
    for _ in 0..60 {
        f.step(
            1. / 60.,
            Input {
                level: 1.,
                balance: 1.,
            },
        );
    }
    for l in f.frame(900., 740., true, true).lobes {
        assert_eq!(l.alpha, 0.);
        assert!(l.lab.iter().all(|v| v.is_finite()));
    }
}
#[test]
fn long_overlap_is_bounded_and_finite() {
    let mut f = Field::new();
    for _ in 0..36000 {
        f.step(
            1.0 / 60.0,
            Input {
                level: 1.0,
                balance: 1.0,
            },
        );
        let frame = f.frame(1160.0, 740.0, true, true);
        for l in frame.lobes {
            assert!(l.x.is_finite() && l.y.is_finite());
            assert!(l.sigma < 0.5 && l.alpha <= 2.0);
        }
    }
}
