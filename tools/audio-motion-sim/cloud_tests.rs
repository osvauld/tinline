    let mut f = Field::new();
    f.set_state(State::Incoming);
    for _ in 0..30 {
        f.step(1.0 / 60.0, Input::default());
    }
    let frame = f.frame(390., 844., true, false);
    assert!((frame.tau - 0.4403250899997235).abs() < 1e-10);
    assert!((frame.warp - 0.11975860250030843).abs() < 1e-10);
