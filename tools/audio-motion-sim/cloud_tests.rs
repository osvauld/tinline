#[test]
fn frequency_changes_shape_at_equal_intensity() {
    let mut low = Field::new();
    let mut high = Field::new();
    for _ in 0..120 {
        low.step(
            1. / 60.,
            Input {
                level: 0.7,
                balance: 0.,
            },
        );
        high.step(
            1. / 60.,
            Input {
                level: 0.7,
                balance: 1.,
            },
        );
    }
    let a = low.frame(900., 740., false, false);
    let b = high.frame(900., 740., false, false);
    assert!((a.lobes[0].sigma - b.lobes[0].sigma).abs() > 0.005);
    assert!((a.lobes[4].sigma - b.lobes[4].sigma).abs() > 0.005);
}
#[test]
fn ordinary_speech_is_visible_against_resting_clouds() {
    let mut f = Field::new();
    let quiet = f.frame(900., 740., false, false);
    for _ in 0..20 {
        f.step(
            1. / 60.,
            Input {
                level: 0.35,
                balance: 0.1,
            },
        );
    }
    let talking = f.frame(900., 740., false, false);
    let swell = talking
        .lobes
        .iter()
        .zip(quiet.lobes)
        .map(|(a, b)| a.sigma - b.sigma)
        .fold(0_f64, f64::max);
    let coverage = talking
        .lobes
        .iter()
        .zip(quiet.lobes)
        .map(|(a, b)| a.alpha - b.alpha)
        .fold(0_f64, f64::max);
    assert!(swell >= 0.035, "ordinary speech swell only {swell}");
    assert!(coverage >= 0.20, "ordinary speech coverage only {coverage}");
    assert!(
        talking.warp - quiet.warp >= 0.015,
        "no audible texture deformation"
    );
}
