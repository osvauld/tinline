//! Writers for each consumer. Every icon is split by role into one path per role, so a UI can draw the
//! string in its own colour (gold, like the logo) or everything in one colour.

use crate::icons::{all, Icon, Kind, Role, Tier, STROKE};
use crate::path::num;

const HEADER: &str = "GENERATED by `cargo run -p tin-icons --bin tin-icons-gen`. Do not edit: change crates/tin-icons/src/icons.rs.";

/// One icon at one tier, merged by role: (lines, fills, strings) as path data.
pub struct Merged {
    pub lines: String,
    pub fills: String,
    pub strings: String,
}

pub fn merged(icon: &Icon) -> Merged {
    let join = |r: Role| icon.parts.iter().filter(|p| p.role == r).map(|p| p.path.d()).collect::<Vec<_>>().join("");
    Merged { lines: join(Role::Line), fills: join(Role::Fill), strings: join(Role::String) }
}

/// [16, 20, 24] tiers of every icon, in set order.
pub fn tiers() -> Vec<(Icon, [Merged; 3])> {
    let sets: Vec<Vec<Icon>> = Tier::ALL.iter().map(|&t| all(t)).collect();
    (0..sets[0].len())
        .map(|i| (sets[2][i].clone(), [merged(&sets[0][i]), merged(&sets[1][i]), merged(&sets[2][i])]))
        .collect()
}

fn kind(k: Kind) -> &'static str {
    match k {
        Kind::Mark => "mark",
        Kind::Ours => "ours",
        Kind::Kept => "kept",
        Kind::Retire => "retire",
    }
}

fn upper(name: &str) -> String {
    name.replace('-', "_").to_uppercase()
}

fn pascal(name: &str) -> String {
    name.split('-').map(|w| {
        let mut c = w.chars();
        c.next().map(|f| f.to_uppercase().collect::<String>() + c.as_str()).unwrap_or_default()
    }).collect()
}

/// Rust for iced (resvg): markup bodies with explicit paint, tinted after rasterising.
pub fn rust() -> String {
    let mut s = format!(
        "// {HEADER}\n// Tinline line icons on a 24 grid, three size tiers (16, 20, 24 px). Black SVG bodies; tint the pixels.\n\n\
         /// One icon at one tier. `body` is everything but the string; `string` is the string alone (may be empty).\n\
         #[derive(Clone, Copy, Debug)]\npub struct Glyph {{\n    pub body: &'static str,\n    pub string: &'static str,\n}}\n\n\
         /// Root `<svg>` paint for stroked parts.\n\
         pub const STROKE: &str = r##\"fill=\"none\" stroke=\"#000\" stroke-width=\"{}\" stroke-linecap=\"round\" stroke-linejoin=\"round\"\"##;\n\n\
         /// Nearest designed tier for a display size in logical px: 0 = 16, 1 = 20, 2 = 24.\n\
         pub fn tier(px: f32) -> usize {{\n    if px < 18.0 {{ 0 }} else if px < 22.0 {{ 1 }} else {{ 2 }}\n}}\n\n",
        num(STROKE)
    );
    let t = tiers();
    s.push_str("pub const NAMES: &[&str] = &[\n");
    for (icon, _) in &t {
        s.push_str(&format!("    \"{}\",\n", icon.name));
    }
    s.push_str("];\n\npub fn get(name: &str, px: f32) -> Option<Glyph> {\n    let t = tier(px);\n    Some(match name {\n");
    for (icon, _) in &t {
        s.push_str(&format!("        \"{}\" => {}[t],\n", icon.name, upper(icon.name)));
    }
    s.push_str("        _ => return None,\n    })\n}\n");
    let markup = |m: &Merged| {
        let mut b = String::new();
        if !m.lines.is_empty() { b.push_str(&format!("<path d=\"{}\"/>", m.lines)) }
        if !m.fills.is_empty() { b.push_str(&format!("<path fill=\"#000\" stroke=\"none\" d=\"{}\"/>", m.fills)) }
        let st = if m.strings.is_empty() { String::new() } else { format!("<path d=\"{}\"/>", m.strings) };
        (b, st)
    };
    for (icon, m) in &t {
        let g: Vec<String> = m.iter().map(|m| {
            let (b, st) = markup(m);
            format!("Glyph {{ body: r##\"{b}\"##, string: r##\"{st}\"## }}")
        }).collect();
        let note = if icon.note.is_empty() { String::new() } else { format!(" {}", icon.note) };
        s.push_str(&format!("\n/// `{}` ({}).{}\n", icon.name, kind(icon.kind), note));
        if g[0] == g[1] && g[1] == g[2] {
            s.push_str(&format!("pub const {}: [Glyph; 3] = [{}; 3];\n", upper(icon.name), g[2]));
        } else {
            s.push_str(&format!("pub const {}: [Glyph; 3] = [\n    {},\n    {},\n    {},\n];\n", upper(icon.name), g[0], g[1], g[2]));
        }
    }
    s
}

/// Kotlin for Compose: ImageVectors built on first use from the same path data.
pub fn kotlin() -> String {
    let mut s = format!(
        "// {HEADER}\npackage com.osvauld.p2p\n\n\
import androidx.compose.ui.graphics.Color\nimport androidx.compose.ui.graphics.SolidColor\nimport androidx.compose.ui.graphics.StrokeCap\n\
import androidx.compose.ui.graphics.StrokeJoin\nimport androidx.compose.ui.graphics.vector.ImageVector\nimport androidx.compose.ui.graphics.vector.PathParser\n\
import androidx.compose.ui.unit.Dp\nimport androidx.compose.ui.unit.dp\n\n\
/** One icon at one size tier. [all] is the whole glyph in one colour; [body] and [string] split it so the string can be gold. */\n\
class TinGlyph(val all: ImageVector, val body: ImageVector, val string: ImageVector?)\n\n\
/** A Tinline line icon (crates/tin-icons). Tiers are designed for 16, 20 and 24 dp; [at] picks the nearest. */\n\
class TinIcon internal constructor(private val name: String, private val tiers: Array<Array<String>>) {{\n\
    private val cache = arrayOfNulls<TinGlyph>(3)\n\n\
    fun at(size: Dp): TinGlyph {{\n\
        val t = when {{ size.value < 18f -> 0; size.value < 22f -> 1; else -> 2 }}\n\
        return cache[t] ?: build(tiers[t]).also {{ cache[t] = it }}\n\
    }}\n\n\
    private fun build(p: Array<String>): TinGlyph {{\n\
        val (lines, fills, strings) = p\n\
        return TinGlyph(vec(lines + strings, fills), vec(lines, fills), if (strings.isEmpty()) null else vec(strings, \"\"))\n\
    }}\n\n\
    private fun vec(lines: String, fills: String): ImageVector =\n\
        ImageVector.Builder(name, 24.dp, 24.dp, 24f, 24f).apply {{\n\
            if (lines.isNotEmpty()) addPath(\n\
                PathParser().parsePathString(lines).toNodes(), fill = null, stroke = SolidColor(Color.Black),\n\
                strokeLineWidth = {}f, strokeLineCap = StrokeCap.Round, strokeLineJoin = StrokeJoin.Round,\n\
            )\n\
            if (fills.isNotEmpty()) addPath(PathParser().parsePathString(fills).toNodes(), fill = SolidColor(Color.Black))\n\
        }}.build()\n\
}}\n\nobject TinIcons {{\n",
        num(STROKE)
    );
    for (icon, m) in tiers() {
        let tier = |m: &Merged| format!("arrayOf(\"{}\", \"{}\", \"{}\")", m.lines, m.fills, m.strings);
        s.push_str(&format!(
            "    /** `{}` ({}). {} */\n    val {} = TinIcon(\"{}\", arrayOf(\n        {},\n        {},\n        {},\n    ))\n",
            icon.name, kind(icon.kind), icon.note, pascal(icon.name), icon.name, tier(&m[0]), tier(&m[1]), tier(&m[2])
        ));
    }
    s.push_str("}\n");
    s
}

/// TypeScript for the playground: markup for an `<svg class="i">` whose CSS sets stroke and fill.
pub fn ts() -> String {
    let mut s = format!(
        "// {HEADER}\n// Tinline line icons, 24 grid, tiers [16, 20, 24]. Markup classes: `f` = filled part, `str` = the string.\n\n\
export type TinGlyph = {{ body: string; string: string }};\nexport const TIN_STROKE = {};\n\
export const tinTier = (px: number) => (px < 18 ? 0 : px < 22 ? 1 : 2);\n\nexport const TIN: Record<string, [TinGlyph, TinGlyph, TinGlyph]> = {{\n",
        num(STROKE)
    );
    for (icon, m) in tiers() {
        let g = |m: &Merged| {
            let mut b = String::new();
            if !m.lines.is_empty() { b.push_str(&format!("<path d=\\\"{}\\\"/>", m.lines)) }
            if !m.fills.is_empty() { b.push_str(&format!("<path class=\\\"f\\\" d=\\\"{}\\\"/>", m.fills)) }
            let st = if m.strings.is_empty() { String::new() } else { format!("<path class=\\\"str\\\" d=\\\"{}\\\"/>", m.strings) };
            format!("{{ body: \"{b}\", string: \"{st}\" }}")
        };
        s.push_str(&format!("  \"{}\": [{}, {}, {}],\n", icon.name, g(&m[0]), g(&m[1]), g(&m[2])));
    }
    s.push_str("};\n");
    s
}

/// A review sheet: every icon at 16, 20 and 24 px (their own tiers) and the 24 tier at 3×, string in gold.
pub fn contact_sheet() -> String {
    let t = tiers();
    let (row, w) = (84.0, 1040.0);
    let h = 56.0 + row * t.len() as f64;
    let mut s = format!(
        "<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"{w}\" height=\"{h}\" viewBox=\"0 0 {w} {h}\" font-family=\"ui-monospace, monospace\">\n\
<desc>{HEADER}</desc>\n<rect width=\"100%\" height=\"100%\" fill=\"#f5f6f3\"/>\n\
<text x=\"20\" y=\"32\" font-size=\"15\" font-weight=\"600\" fill=\"#17201d\">Tinline line icons · 16 · 20 · 24 · 72 (24 tier at 3×)</text>\n"
    );
    let glyph = |m: &Merged, x: f64, y: f64, px: f64| {
        let k = px / 24.0;
        let mut g = format!(
            "<g transform=\"translate({x} {y}) scale({k})\" fill=\"none\" stroke-width=\"{}\" stroke-linecap=\"round\" stroke-linejoin=\"round\">",
            num(STROKE)
        );
        if !m.lines.is_empty() { g.push_str(&format!("<path stroke=\"#17201d\" d=\"{}\"/>", m.lines)) }
        if !m.fills.is_empty() { g.push_str(&format!("<path fill=\"#17201d\" d=\"{}\"/>", m.fills)) }
        if !m.strings.is_empty() { g.push_str(&format!("<path stroke=\"#c98a1e\" d=\"{}\"/>", m.strings)) }
        g.push_str("</g>");
        g
    };
    for (i, (icon, m)) in t.iter().enumerate() {
        let y = 56.0 + row * i as f64;
        if i % 2 == 1 {
            s.push_str(&format!("<rect x=\"0\" y=\"{y}\" width=\"{w}\" height=\"{row}\" fill=\"#ecefeb\"/>\n"));
        }
        let mid = y + row / 2.0;
        s.push_str(&format!("<text x=\"20\" y=\"{}\" font-size=\"13\" fill=\"#17201d\">{}</text>", mid + 4.0, icon.name));
        s.push_str(&format!("<text x=\"120\" y=\"{}\" font-size=\"11\" fill=\"#4d5853\">{}</text>", mid + 4.0, kind(icon.kind)));
        s.push_str(&glyph(&m[0], 190.0, mid - 8.0, 16.0));
        s.push_str(&glyph(&m[1], 230.0, mid - 10.0, 20.0));
        s.push_str(&glyph(&m[2], 274.0, mid - 12.0, 24.0));
        s.push_str(&glyph(&m[2], 330.0, mid - 36.0, 72.0));
        let note: String = icon.note.chars().take(90).collect();
        s.push_str(&format!("<text x=\"430\" y=\"{}\" font-size=\"11\" fill=\"#4d5853\">{}</text>\n", mid + 4.0, xml(&note)));
    }
    s.push_str("</svg>\n");
    s
}

fn xml(s: &str) -> String {
    s.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;")
}

