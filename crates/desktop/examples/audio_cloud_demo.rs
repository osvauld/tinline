#[derive(Clone, Copy, Debug, PartialEq)]
enum Source {
    Silence,
    Phrases,
    Low,
    High,
    Mix,
    Microphone,
}
#[derive(Clone, Debug)]
enum Msg {
    Tick,
    Scene(bool),
    Texture(bool),
    Dark,
    Reduced,
    Pause,
    Source(Source),
    State(State),
    Mic,
    Mute,
    Speaker,
    Sensitivity(f32),
}
struct Demo {
    field: Field,
    group: bool,
    clouds: bool,
    dark: bool,
    paused: bool,
    muted: bool,
    speaker: bool,
    source: Source,
    extractor: spectral::Extractor,
    sample: u64,
    elapsed: f64,
    call_elapsed: f64,
    mic: Option<mic::Mic>,
    mic_input: Input,
    sensitivity: f32,
    note: String,
    last_tick: Instant,
    speaking: [bool; 4],
    smoke: bool,
    ticks: u32,
}
impl Default for Demo {
    fn default() -> Self {
        Self {
            field: Field::new(),
            group: false,
            clouds: false,
            dark: false,
            paused: false,
            muted: false,
            speaker: false,
            source: Source::Phrases,
            extractor: spectral::Extractor::new(),
            sample: 0,
            elapsed: 0.,
            call_elapsed: 0.,
            mic: None,
            mic_input: Input::default(),
            sensitivity: 1.6,
            note: "Microphone off. Simulated speech; no audio saved or sent.".into(),
            last_tick: Instant::now(),
            speaking: [false; 4],
            smoke: std::env::args().any(|a| a == "--smoke"),
            ticks: 0,
        }
    }
}
impl Demo {
    fn stop_mic(&mut self) {
        self.mic = None;
        self.mic_input = Input::default();
    }
    fn update(&mut self, msg: Msg) -> Task<Msg> {
        match msg {
            Msg::Tick if !self.paused => {
                let dt = self.last_tick.elapsed().as_secs_f64().min(0.1);
                self.last_tick = Instant::now();
                self.elapsed += dt;
                if self.field.state.speech() {
                    self.call_elapsed += dt;
                }
                self.speaking = [false; 4];
                if self.mic.as_ref().is_some_and(|m| m.failed()) {
                    self.stop_mic();
                    self.note = "Microphone error — stopped. Check device and retry.".into();
                }
                let input = match self.source {
                    Source::Microphone => {
                        if let Some(m) = &mut self.mic {
                            if let Some(o) = m.poll() {
                                self.mic_input = if o.audible && !self.muted {
                                    cloud::microphone_input(
                                        o.level,
                                        o.audible,
                                        o.features.map_or(0.5, |f| f.high + 0.5 * f.mid),
                                        self.sensitivity as f64,
                                    )
                                } else {
                                    Input::default()
                                };
                                self.note = format!(
                                    "Local mic · {} (-dBov) · visual drive {:.0}%\nDropped blocks {} · no audio saved/sent.",
                                    o.level,
                                    self.mic_input.level * 100.,
                                    m.drops()
                                );
                            }
                            if !m.fresh() {
                                self.mic_input = Input::default();
                            }
                        } else {
                            self.mic_input = Input::default();
                        }
                        self.speaking[0] = self.mic_input.level > 0.05;
                        self.mic_input
                    }
                    Source::Silence => Input::default(),
                    source => {
                        let phrases = source == Source::Phrases;
                        let low = source != Source::High;
                        let high = source != Source::Low;
                        let pcm = fixture::tone_pcm(self.sample, low, high);
                        self.sample += 1600;
                        let spectrum = self.extractor.push(&pcm);
                        let gate = if phrases {
                            self.elapsed % 4.2 < 2.7
                        } else {
                            true
                        };
                        let level: f64 = if gate { 0.5 } else { 0. };
                        // Simulated remote Alex; local mute never quiets this contribution.
                        self.speaking[1] = gate;
                        if self.group && phrases {
                            self.speaking[2] = (self.elapsed + 1.5) % 6.4 < 1.8;
                        }
                        Input {
                            level: (level + if self.speaking[2] { 0.2 } else { 0. }).min(1.),
                            balance: spectrum.map_or(0.5, |f| f.high + 0.5 * f.mid),
                        }
                    }
                };
                if !self.field.state.speech() {
                    self.speaking = [false; 4];
                }
                self.field.step(dt, input);
                self.ticks += 1;
                if self.smoke {
                    match self.ticks {
                        15 => self.group = true,
                        30 => {
                            self.clouds = true;
                            self.dark = true;
                        }
                        45 => self.field.set_state(State::Connecting),
                        60 => {
                            self.field.reduced = true;
                            self.field.set_state(State::Active);
                        }
                        75 => self.field.set_state(State::Ended),
                        90 => return iced::exit(),
                        _ => {}
                    }
                }
            }
            Msg::Scene(group) => self.group = group,
            Msg::Texture(clouds) => self.clouds = clouds,
            Msg::Dark => self.dark = !self.dark,
            Msg::Reduced => self.field.reduced = !self.field.reduced,
            Msg::Pause => {
                self.paused = !self.paused;
                self.last_tick = Instant::now();
                if self.paused {
                    self.stop_mic();
                    self.note =
                        "Paused. Capture stopped; Start microphone is required again.".into();
                }
            }
            Msg::Source(source) => {
                self.stop_mic();
                self.source = source;
                self.extractor.reset();
                self.speaking = [false; 4];
                self.note = "Microphone off. Synthetic PCM is analysed but never played.".into();
            }
            Msg::State(state) => {
                if state.speech() && !self.field.state.speech() {
                    self.call_elapsed = 0.;
                }
                self.field.set_state(state);
                if !state.speech() {
                    self.stop_mic();
                }
            }
            Msg::Mic => {
                if self.mic.is_some() {
                    self.stop_mic();
                    self.note = "Microphone stopped. No audio saved or sent.".into();
                } else {
                    match mic::Mic::start() {
                        Ok(m) => {
                            self.mic = Some(m);
                            self.source = Source::Microphone;
                            self.muted = false;
                            self.paused = false;
                            if !self.field.state.speech() {
                                self.call_elapsed = 0.;
                            }
                            self.field.set_state(State::Active);
                            self.last_tick = Instant::now();
                            self.note = "Default microphone starting — local only.".into();
                        }
                        Err(e) => self.note = format!("Microphone not started: {e}"),
                    }
                }
            }
            Msg::Mute => {
                self.muted = !self.muted;
                if self.muted {
                    self.stop_mic();
                    self.note =
                        "Local mic muted; capture released. Remote simulation remains audible."
                            .into();
                }
            }
            Msg::Speaker => self.speaker = !self.speaker,
            Msg::Sensitivity(value) => self.sensitivity = value,
            _ => {}
        }
        Task::none()
    }
    fn ink(&self) -> Color {
        if self.dark {
            Color::from_rgb8(230, 236, 233)
        } else {
            Color::from_rgb8(23, 32, 29)
        }
    }
    fn avatar(
        &self,
        name: &'static str,
        initials: &'static str,
        index: usize,
        size: f32,
    ) -> Element<'_, Msg> {
        let active = self.speaking[index] && self.field.state.speech();
        let dark = self.dark;
        let ink = self.ink();
        let pic = container(
            text(initials)
                .size(size * 0.32)
                .font(ui::SANS_SEMI)
                .color(ink),
        )
        .width(size)
        .height(size)
        .center_x(size)
        .center_y(size)
        .style(move |_| container::Style {
            background: Some(
                if dark {
                    Color::from_rgba(0.15, 0.43, 0.37, if active { 0.85 } else { 0.60 })
                } else {
                    Color::from_rgba(0.64, 0.81, 0.73, if active { 0.95 } else { 0.65 })
                }
                .into(),
            ),
            border: Border {
                radius: (size / 2.).into(),
                ..Default::default()
            },
            ..Default::default()
        });
        column![
            pic,
            container(text(name).size(15).font(ui::SANS_SEMI).color(ink))
                .height(24)
                .center_x(Length::Fill),
            container(
                text(if index == 0 && self.muted {
                    "Muted"
                } else if active {
                    "Speaking"
                } else {
                    " "
                })
                .size(12)
                .color(ink)
            )
            .height(20)
            .center_x(Length::Fill)
        ]
        .spacing(8)
        .align_x(alignment::Horizontal::Center)
        .width(if self.group { 180. } else { 400. })
        .into()
    }
    fn ctl(
        &self,
        icon: call_icons::Kind,
        label: &'static str,
        message: Msg,
        end: bool,
    ) -> Element<'_, Msg> {
        let selected = matches!(icon, call_icons::Kind::MicOff | call_icons::Kind::SpeakerOn);
        let ink = if end || selected {
            if self.dark && !end {
                Color::from_rgb8(23, 32, 29)
            } else {
                Color::WHITE
            }
        } else {
            self.ink()
        };
        let dark = self.dark;
        let glyph = canvas(call_icons::Glyph {
            kind: icon,
            colour: ink,
        })
        .width(28)
        .height(28);
        let b = button(container(glyph).center_x(64).center_y(64))
            .padding(0)
            .width(64)
            .height(64)
            .on_press(message)
            .style(move |_, status| {
                let hover = matches!(status, button::Status::Hovered);
                button::Style {
                    background: Some(
                        if end {
                            Color::from_rgb8(176, 49, 47)
                        } else if selected {
                            if dark {
                                Color::from_rgb8(230, 236, 233)
                            } else {
                                Color::from_rgb8(23, 32, 29)
                            }
                        } else if dark {
                            Color::from_rgb8(
                                if hover { 54 } else { 40 },
                                if hover { 65 } else { 50 },
                                if hover { 59 } else { 45 },
                            )
                        } else {
                            Color::from_rgb8(
                                if hover { 229 } else { 241 },
                                if hover { 234 } else { 243 },
                                if hover { 228 } else { 236 },
                            )
                        }
                        .into(),
                    ),
                    text_color: ink,
                    border: Border {
                        radius: 32.into(),
                        ..Default::default()
                    },
                    ..Default::default()
                }
            });
        column![
            b,
            container(text(label).size(13).color(self.ink()))
                .width(92)
                .height(20)
                .center_x(92)
        ]
        .align_x(alignment::Horizontal::Center)
        .spacing(8)
        .width(92)
        .into()
    }
    fn call(&self) -> Element<'_, Msg> {
        let ink = self.ink();
        let identity: Element<'_, Msg> = if self.group {
            column![
                container(text("Weekend hike").font(ui::SANS_SEMI).size(28).color(ink))
                    .height(40)
                    .center_x(Length::Fill),
                container(
                    text(if self.field.state.speech() {
                        "4 people in the call"
                    } else {
                        self.field.state.label()
                    })
                    .size(15)
                    .color(ink)
                )
                .height(26)
                .center_x(Length::Fill),
                Space::new().height(Length::Fill),
                row![
                    self.avatar("You", "Y", 0, 88.),
                    self.avatar("Alexandria", "AM", 1, 88.)
                ]
                .spacing(28)
                .align_y(alignment::Vertical::Center),
                row![
                    self.avatar("Maya", "M", 2, 88.),
                    self.avatar("Eleanor", "E", 3, 88.)
                ]
                .spacing(28)
                .align_y(alignment::Vertical::Center),
                Space::new().height(Length::Fill),
            ]
            .align_x(alignment::Horizontal::Center)
            .spacing(18)
            .height(Length::Fill)
            .into()
        } else {
            column![
                Space::new().height(Length::Fill),
                self.avatar("Alexandria Montgomery-Wellington", "AM", 1, 120.),
                container(text(self.field.state.label()).size(17).color(ink))
                    .height(28)
                    .center_x(Length::Fill),
                Space::new().height(Length::Fill),
            ]
            .align_x(alignment::Horizontal::Center)
            .spacing(20)
            .height(Length::Fill)
            .into()
        };
        let minutes = self.call_elapsed as u32 / 60;
        let seconds = self.call_elapsed as u32 % 60;
        let timer = if self.field.state.speech() {
            format!("{minutes:02}:{seconds:02}")
        } else {
            " ".into()
        };
        let controls = row![
            self.ctl(
                if self.muted {
                    call_icons::Kind::MicOff
                } else {
                    call_icons::Kind::Mic
                },
                if self.muted { "Unmute" } else { "Mute" },
                Msg::Mute,
                false
            ),
            self.ctl(
                call_icons::Kind::Hangup,
                if self.group { "Leave" } else { "End" },
                Msg::State(State::Ended),
                true
            ),
            self.ctl(
                if self.speaker {
                    call_icons::Kind::SpeakerOn
                } else {
                    call_icons::Kind::Speaker
                },
                if self.speaker {
                    "Speaker on"
                } else {
                    "Speaker"
                },
                Msg::Speaker,
                false
            ),
        ]
        .spacing(22)
        .align_y(alignment::Vertical::Center);
        let overlay = container(
            column![
                container(ui::glyph(r##"fill="#000""##, MARK_D, 32., ink))
                    .height(48)
                    .center_x(Length::Fill),
                identity,
                container(text(timer).font(ui::MONO).size(16).color(ink))
                    .height(28)
                    .center_x(Length::Fill),
                container(
                    text(if self.group && self.field.state.speech() {
                        "Hosted by Alex · Host can hear the call"
                    } else {
                        " "
                    })
                    .size(13)
                    .color(ink)
                )
                .height(28)
                .center_x(Length::Fill),
                container(controls).center_x(Length::Fill).height(108),
                container(
                    text(if self.field.state.speech() {
                        "End-to-end encrypted"
                    } else {
                        " "
                    })
                    .size(12)
                    .color(ink)
                )
                .height(24)
                .center_x(Length::Fill),
            ]
            .spacing(8),
        )
        .padding(24)
        .width(Length::Fill)
        .height(Length::Fill);
        stack![
            Shader::new(iced_cloud::Program {
                field: self.field.clone(),
                dark: self.dark,
                clouds: self.clouds,
                group: self.group
            })
            .width(Length::Fill)
            .height(Length::Fill),
            overlay
        ]
        .width(Length::Fill)
        .height(Length::Fill)
        .into()
    }
    fn drawer(&self) -> Element<'_, Msg> {
        let mut states = column![
            text("Call state (silent cues)")
                .font(ui::SANS_SEMI)
                .size(15)
        ]
        .spacing(6);
        for state in [
            State::Calm,
            State::Incoming,
            State::Outgoing,
            State::Connecting,
            State::Active,
            State::Waiting,
            State::Reconnecting,
            State::Ended,
            State::Failed,
        ] {
            let label = if state == State::Waiting {
                "Call waiting"
            } else {
                state.label()
            };
            states = states.push(
                button(label)
                    .width(Length::Fill)
                    .on_press(Msg::State(state)),
            );
        }
        let content=column![
            text("Native call design").size(22).font(ui::SANS_SEMI),
            text("Design-refinement field · Iced/wgpu\nSimulated call; no account or network.").size(13),
            row![button("1:1").on_press(Msg::Scene(false)),button("Group").on_press(Msg::Scene(true))].spacing(8),
            row![button("Fog").on_press(Msg::Texture(false)),button("Clouds").on_press(Msg::Texture(true))].spacing(8),
            button(if self.dark {"Light theme"}else{"Dark theme"}).on_press(Msg::Dark),
            button(if self.field.reduced {"Reduced motion: on"}else{"Reduced motion: off"}).on_press(Msg::Reduced),
            button(if self.paused {"Resume"}else{"Pause"}).on_press(Msg::Pause),
            text("Speech input (no playback)").font(ui::SANS_SEMI).size(15),
            row![button("Silence").on_press(Msg::Source(Source::Silence)),button("Phrases").on_press(Msg::Source(Source::Phrases))].spacing(8),
            row![button("200 Hz").on_press(Msg::Source(Source::Low)),button("4 kHz").on_press(Msg::Source(Source::High)),button("Mix").on_press(Msg::Source(Source::Mix))].spacing(6),
            button(if self.mic.is_some(){"Stop microphone"}else{"Start microphone"}).width(Length::Fill).on_press(Msg::Mic),
            text(format!("Mic sensitivity {:.1}×",self.sensitivity)).size(13),
            slider(0.5..=3.0,self.sensitivity,Msg::Sensitivity).step(0.1),
            container(text(&self.note).size(12)).height(84),
            states,
            text("Experimental speech mapping; call cues / live brand animation are not wired yet.\nStop, Pause, input switch, mute, call end or window close releases capture.\nNo GPU/battery performance claim.").size(12),
        ].spacing(12);
        container(scrollable(content))
            .padding(20)
            .width(300)
            .height(Length::Fill)
            .style(container::rounded_box)
            .into()
    }
    fn view(&self) -> Element<'_, Msg> {
        row![self.call(), self.drawer()].height(Length::Fill).into()
    }
    fn subscription(&self) -> Subscription<Msg> {
        if self.paused || (!self.smoke && self.field.is_idle()) {
            Subscription::none()
        } else {
            iced::time::every(Duration::from_micros(33_333)).map(|_| Msg::Tick)
        }
    }
}
fn main() -> iced::Result {
    if std::env::args().any(|a| a == "--validate-shader") {
        iced_cloud::validate().expect("cloud shader validation");
        return Ok(());
    }
    iced::application(Demo::default, Demo::update, Demo::view)
        .title("Tinline — native Fog / Clouds call preview")
        .subscription(Demo::subscription)
        .theme(|d: &Demo| if d.dark { Theme::Dark } else { Theme::Light })
        .font(ui::FIGTREE_BYTES)
        .font(ui::PLEX_REGULAR_BYTES)
        .default_font(ui::SANS)
        .window(iced::window::Settings {
            min_size: Some(iced::Size::new(780., 740.)),
            ..Default::default()
        })
        .window_size((1160., 820.))
        .run()
}
